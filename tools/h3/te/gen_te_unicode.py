#!/usr/bin/env python3
"""Generate src/h3/te/te_unicode_tables.inc: the Unicode data the H3 text-encoder tokenizer needs.

  kTeCategory    {first, last, flags} ranges, flags 1 = letter (L*), 2 = mark (M*), 4 = number (N*)
  kTeCcc         {first, last, ccc} ranges of non-zero canonical combining class
  kTeDecomp      {cp, offset, length} full canonical decomposition (Hangul syllables excluded,
                 they are algorithmic), code points in kTeDecompData
  kTeCompose     {first, second, composite} canonical composition pairs (primary composites only,
                 composition exclusions and singletons removed), sorted by (first, second)

usage: gen_te_unicode.py OUT.inc
"""
import sys
import unicodedata

SBASE, SCOUNT = 0xAC00, 11172


def ranges(fn):
    out, cur = [], None
    for cp in range(0x110000):
        v = fn(cp)
        if cur and cur[2] == v and cur[1] + 1 == cp:
            cur[1] = cp
            continue
        if cur and cur[2]:
            out.append(tuple(cur))
        cur = [cp, cp, v]
    if cur and cur[2]:
        out.append(tuple(cur))
    return out


def full_decomp(cp):
    d = unicodedata.decomposition(chr(cp))
    if not d or d.startswith("<"):
        return [cp]
    out = []
    for part in d.split():
        out.extend(full_decomp(int(part, 16)))
    return out


def main(path):
    cat = ranges(lambda cp: {"L": 1, "M": 2, "N": 4}.get(unicodedata.category(chr(cp))[0], 0))
    ccc = ranges(lambda cp: unicodedata.combining(chr(cp)))
    decomp, data = [], []
    compose = []
    for cp in range(0x110000):
        if SBASE <= cp < SBASE + SCOUNT:
            continue
        d = unicodedata.decomposition(chr(cp))
        if not d or d.startswith("<"):
            continue
        full = full_decomp(cp)
        decomp.append((cp, len(data), len(full)))
        data.extend(full)
        parts = [int(p, 16) for p in d.split()]
        # primary composite: the canonical pair re-composes under NFC
        if len(parts) == 2 and unicodedata.normalize("NFC", chr(parts[0]) + chr(parts[1])) == chr(cp):
            compose.append((parts[0], parts[1], cp))
    compose.sort()
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/h3/te/gen_te_unicode.py from Unicode %s. Do not edit.\n" % unicodedata.unidata_version)
        f.write("inline constexpr TeRange kTeCategory[] = {\n")
        f.writelines("    {0x%X, 0x%X, %d},\n" % r for r in cat)
        f.write("};\ninline constexpr TeRange kTeCcc[] = {\n")
        f.writelines("    {0x%X, 0x%X, %d},\n" % r for r in ccc)
        f.write("};\ninline constexpr TeDecomp kTeDecomp[] = {\n")
        f.writelines("    {0x%X, %d, %d},\n" % r for r in decomp)
        f.write("};\ninline constexpr std::uint32_t kTeDecompData[] = {\n")
        for i in range(0, len(data), 12):
            f.write("    " + ", ".join("0x%X" % c for c in data[i:i + 12]) + ",\n")
        f.write("};\ninline constexpr TeCompose kTeCompose[] = {\n")
        f.writelines("    {0x%X, 0x%X, 0x%X},\n" % r for r in compose)
        f.write("};\n")
    print(path, "category", len(cat), "ccc", len(ccc), "decomp", len(decomp), "compose", len(compose))


if __name__ == "__main__":
    main(sys.argv[1])
