#!/usr/bin/env python3
"""Print the reference RoPE inverse frequencies of the H3 text encoder as FP32 bit patterns.

The reference computes inv_freq = 1.0 / (theta ** (arange(0, 128, 2).float() / 128)) in FP32
(theta 5e6). Its FP32 pow is not correctly rounded everywhere; a correctly rounded host formula
differs by 1 ulp in some entries, which at positions ~3000 shifts rotary angles by ~1e-4 rad.
The table below is that FP32 result (CPU), embedded in src/h3/te/te_gpu.hip.

usage: python gen_te_rope.py
"""
import torch

inv = 1.0 / (5000000.0 ** (torch.arange(0, 128, 2).float() / 128))
bits = inv.view(torch.int32).tolist()
print("// generated by tools/h3/te/gen_te_rope.py (torch %s)" % torch.__version__)
print("constexpr std::uint32_t kInvFreqBits[64] = {")
for i in range(0, 64, 8):
    print("    " + ", ".join("0x%08XU" % (b & 0xFFFFFFFF) for b in bits[i:i + 8]) + ",")
print("};")
