#!/usr/bin/env python3
# Generates src/glm/prefill/glm_pf_mla_gemm_vopd.inc: one k step of the exact MLA GEMM v3's 8 x 8 register tile.
# Each accumulator keeps fmaf(A[i], W[j], acc[i,j]) for k ascending, from +0. Pair diagonally across adjacent rows
# and columns: (i,j) with (i+1,j^1). Both VGPR source pairs then use different banks, and the destinations (also
# FMAC's SRC2) have opposite parity. A same-row pair would conflict on SRC0. Four row-pair helpers keep individual
# asm operand lists small, as in gen_glm_scores_vopd.py. Registers: acc v8..71, A v72..79, W v80..87.
# ISA: AMD RDNA3 ISA, section 7.6 (Dual Issue VALU), wave32 only:
# https://docs.amd.com/api/khub/documents/UkT_UPQL21KfKAMUBFnZTw/content
# Usage: python tools/gen_glm_mla_gemm_vopd.py > src/glm/prefill/glm_pf_mla_gemm_vopd.inc
ACC, AV, WV, ROWS, COLS = 8, 72, 80, 8, 8


def acc(i, j):
    return ACC + COLS * i + j


seen = set()
for i in range(0, ROWS, 2):
    for j in range(COLS):
        x, y = acc(i, j), acc(i + 1, j ^ 1)
        assert x % 2 != y % 2
        assert (AV + i) % 4 != (AV + i + 1) % 4
        assert (WV + j) % 4 != (WV + (j ^ 1)) % 4
        assert not {x, y} & seen
        seen.update((x, y))
assert seen == set(range(ACC, ACC + ROWS * COLS))

sig = "float (&a)[64], const float (&av)[8], const float (&wv)[8]"
print("// Generated by tools/gen_glm_mla_gemm_vopd.py; do not edit.")
print(f"template <unsigned P> __device__ __forceinline__ void mla_gemm_vopd_rows({sig});")
for p in range(ROWS // 2):
    i = 2 * p
    lines = []
    for j in range(COLS):
        lines.append(f"v_dual_fmac_f32 v{acc(i, j)}, v{AV + i}, v{WV + j} :: "
                     f"v_dual_fmac_f32 v{acc(i + 1, j ^ 1)}, v{AV + i + 1}, v{WV + (j ^ 1)}")
    outs = ", ".join(f'"+{{v{acc(r, j)}}}"(a[{COLS * r + j}])' for r in (i, i + 1) for j in range(COLS))
    ins = ", ".join([*(f'"{{v{AV + r}}}"(av[{r}])' for r in (i, i + 1)),
                     *(f'"{{v{WV + j}}}"(wv[{j}])' for j in range(COLS))])
    print(f"template <> __device__ __forceinline__ void mla_gemm_vopd_rows<{p}>({sig}) {{")
    print('    asm("' + "\\n\\t".join(lines) + '"')
    print(f"        : {outs}")
    print(f"        : {ins});")
    print("}")
