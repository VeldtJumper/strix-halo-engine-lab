#!/usr/bin/env python3
# Generates src/glm/prefill/glm_pf_scores_vopd.inc: the inner step of GLM prefill MLA scores v6 (heads 32, two list
# entries per lane) as hand-paired VOPD.
#
# Scores v5's chains: per (entry x, head h) acc(x, h) = fma(q(h, l), c(x, l), acc(x, h)) for l ascending; one step
# covers 16 latent dims l (i = 0..15). A VOPD pair is the two entries of the same head and dim; they share the q
# value, which is wave-uniform and comes from an SGPR (src0 of both halves):
#   X: v_dual_fmac_f32 acc(0, h), q(h, i), c(0, i)
#   Y: v_dual_fmac_f32 acc(1, h), q(h, i), c(1, i)
# v_dual_fmac_f32 is the single-rounding FMA of fmaf, and every accumulator's chain keeps its order: same bits.
# Compact layout (96 VGPRs): acc(x, h) = v(8 + 2 h + x), c(x, i) = v(72 + 2 i + x), so each pair has destinations of
# opposite parity and its two vsrc1 in different banks. One function per group of four heads (h = 4 p .. 4 p + 3),
# interleaved per dim: four independent pairs between two uses of an accumulator.
# Usage: python tools/gen_glm_scores_vopd.py > src/glm/prefill/glm_pf_scores_vopd.inc
ACC, COEF, HEADS, DIMS, GROUP = 8, 72, 32, 16, 4
QN = ["qa", "qb", "qc", "qd"]


def acc(x, h):
    return ACC + 2 * h + x


def coef(x, i):
    return COEF + 2 * i + x


for h in range(HEADS):
    assert acc(0, h) % 2 == 0 and acc(1, h) % 2 == 1
for i in range(DIMS):
    assert coef(0, i) % 4 != coef(1, i) % 4

sig = "float (&a)[64], const float (&c)[32], const SVec16& qa, const SVec16& qb, const SVec16& qc, const SVec16& qd"
print("// Generated by tools/gen_glm_scores_vopd.py; do not edit.")
print(f"template <unsigned P> __device__ __forceinline__ void scores_vopd_heads({sig});")
for p in range(HEADS // GROUP):
    hs = [GROUP * p + k for k in range(GROUP)]
    lines = []
    for i in range(DIMS):
        for h, q in zip(hs, QN):
            lines.append(f"v_dual_fmac_f32 v{acc(0, h)}, %[{q}{i}], v{coef(0, i)} :: "
                         f"v_dual_fmac_f32 v{acc(1, h)}, %[{q}{i}], v{coef(1, i)}")
    outs = ", ".join(f'"+{{v{acc(x, h)}}}"(a[{2 * h + x}])' for h in hs for x in range(2))
    ins = ", ".join(f'"{{v{coef(x, i)}}}"(c[{2 * i + x}])' for i in range(DIMS) for x in range(2))
    sins = ", ".join(f'[{q}{i}] "s"({q}[{i}])' for q in QN for i in range(DIMS))
    print(f"template <> __device__ __forceinline__ void scores_vopd_heads<{p}>({sig}) {{")
    print('    asm("' + "\\n\\t".join(lines) + '"')
    print(f"        : {outs}")
    print(f"        : {ins}, {sins});")
    print("}")
